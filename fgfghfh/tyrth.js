// Введення трьох чисел
let a = Number(prompt("Введіть перше число:"));
let b = Number(prompt("Введіть друге число:"));
let c = Number(prompt("Введіть третє число:"));

// 1. Середнє арифметичне
let average = (a + b + c) / 3;
console.log("Середнє арифметичне:", average);

// 2. Арифметичні операції
console.log("Модуль першого числа:", Math.abs(a));
console.log("Округлення другого в більшу сторону:", Math.ceil(b));
console.log("Округлення третього в меншу сторону:", Math.floor(c));
console.log("Перше число у квадраті:", a ** 2);

// 3. Перевірка подільності
console.log("a ділиться на 5:", a % 5 === 0);
console.log("b ділиться на 7:", b % 7 === 0);

// 4. Перевірка існування трикутника
if (a + b > c && a + c > b && b + c > a) {
    console.log("Трикутник може існувати");
} else {
    console.log("Трикутник не може існувати");
}
